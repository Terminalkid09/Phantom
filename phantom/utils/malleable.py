"""Malleable C2 profile generator for Phantom Beacon.

Generates the C++ header `malleable_config.h` from a JSON profile file so
the beacon's network fingerprint is fully customizable: URI paths, user-agent
pool, sleep cadence, headers, and traffic shape parameters.

The engine can also generate `malleable_config.h` from the `--set key=value`
convenience interface on the command line.
"""

import json as _json
import os as _os
import secrets as _secrets
import hashlib as _hashlib
from typing import Optional as _Optional


