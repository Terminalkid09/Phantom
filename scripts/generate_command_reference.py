#!/usr/bin/env python3
"""Generate docs/COMMAND_REFERENCE.md from the live Phantom registries.

The reference used to be a hand-maintained snapshot: it described itself as
generated, but no generator existed, and whole module command tables were
missing. This script makes the claim true. `--check` is used by the test
suite so a command added to the code cannot silently disappear from the docs.
"""
from __future__ import annotations

import argparse
import importlib
import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from phantom.core.c2_shell import C2Shell  # noqa: E402
from phantom.core.shell.registry import iter_commands  # noqa: E402
from phantom.main import build_parser  # noqa: E402
from phantom.modules.base_module import BaseModule  # noqa: E402

OUT = ROOT / "docs" / "COMMAND_REFERENCE.md"

MODULES = (
    ("scan", "phantom.modules.scan", "ScanModule"),
    ("osint", "phantom.modules.osint", "OsintModule"),
    ("wifi", "phantom.modules.wifi", "WifiModule"),
    ("web", "phantom.modules.web", "WebModule"),
    ("brute", "phantom.modules.brute", "BruteModule"),
    ("exploit", "phantom.modules.exploit", "ExploitModule"),
    ("payload", "phantom.modules.payload", "PayloadModule"),
    ("handler", "phantom.modules.handler", "HandlerModule"),
    ("analyzer", "phantom.modules.analyzer", "AnalyzerModule"),
    ("pivot", "phantom.modules.pivot", "PivotModule"),
    ("wordlist", "phantom.modules.wordlist", "WordlistModule"),
    ("report", "phantom.modules.report", "ReportModule"),
)


def _cell(value: str) -> str:
    return " ".join(str(value or "").split()).replace("|", "\\|")


def _summary(function: object) -> str:
    """The first paragraph of a handler docstring, table-safe."""
    doc = inspect.getdoc(function) or ""
    paragraph: list[str] = []
    for line in doc.splitlines():
        line = line.strip()
        if not line:
            if paragraph:
                break
            continue
        paragraph.append(line)
    return _cell(" ".join(paragraph)) or "-"


def _typed(name: str) -> str:
    """The shells accept the hyphenated spelling; show the one to type."""
    return name.replace("_", "-")


def _row(name: str, description: str) -> str:
    return f"| `{name}` | {description} |"


def _table(rows: list[str]) -> list[str]:
    return ["| Command | What it does |", "|---|---|", *rows]


def _manual_rows() -> list[str]:
    return [_row(_typed(name), _summary(handler))
            for name, handler in iter_commands()]


def _common_module_rows() -> list[str]:
    rows = [
        _row(_typed(name[3:]), _summary(handler))
        for name, handler in BaseModule.__dict__.items()
        if name.startswith("do_") and callable(handler)
    ]
    rows.append(_row("help", "List available commands or show detailed help."))
    return sorted(rows)


def _module_rows(module_class: type) -> list[str]:
    return [
        _row(_typed(name[3:]), _summary(handler))
        for name, handler in sorted(module_class.__dict__.items())
        if name.startswith("do_") and callable(handler)
    ]


def _c2_rows() -> list[str]:
    return [
        _row(_typed(name[3:]), _summary(handler))
        for name, handler in sorted(C2Shell.__dict__.items())
        if name.startswith("do_") and callable(handler)
    ]


def _auto_rows() -> list[str]:
    rows = []
    for action in build_parser()._actions:
        names = [name for name in action.option_strings
                 if name not in ("-h", "--help")]
        if not names:
            continue
        label = " / ".join(f"`{name}`" for name in names)
        rows.append(f"| {label} | {_cell(action.help or '-')} |")
    return rows


def render() -> str:
    lines = [
        "# Phantom command reference",
        "",
        "<!-- Generated by scripts/generate_command_reference.py. Do not edit. -->",
        "",
        "Generated from the live shell registry, every module's `do_*` handlers,",
        "the C2 shell and `phantom.main.build_parser()`. Regenerate with:",
        "",
        "```bash",
        "python scripts/generate_command_reference.py",
        "```",
        "",
        "The command column uses the hyphenated spelling the shells accept.",
        "`help <command>` prints the same text shown here.",
        "",
        "## Manual shell commands",
        "",
        *_table(_manual_rows()),
        "",
        "## Common module commands",
        "",
        "Available inside every `use <module>` session.",
        "",
        *_table(_common_module_rows()),
        "",
        "## Module-specific commands",
        "",
    ]
    for module_name, module_path, class_name in MODULES:
        module_class = getattr(importlib.import_module(module_path), class_name)
        rows = _module_rows(module_class)
        lines.extend([f"### `{module_name}`", ""])
        if rows:
            lines.extend(_table(rows))
        else:
            lines.append("_No module-specific commands; use `suggest`, `run` or `preview`._")
        lines.append("")
    lines.extend([
        "## AUTO-MODE flags (`phantom --auto <target> ...`)",
        "",
        "| Flag | What it does |",
        "|---|---|",
        *_auto_rows(),
        "",
        "## C2 shell commands",
        "",
        *_table(_c2_rows()),
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the checked-in file is stale")
    args = parser.parse_args()
    generated = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != generated:
            print(f"{OUT.relative_to(ROOT)} is stale; run "
                  "`python scripts/generate_command_reference.py`",
                  file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
